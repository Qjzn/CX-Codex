import { spawnSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as esbuild from 'esbuild'

// Behaviour verification for the K1-1 pure thread -> task board projection.
// Bundles the real source module with the already-installed esbuild and runs the bundled entry in a
// fresh node process, so DOM/Vue/browser gear is never involved.
const repoRoot = resolve(fileURLToPath(new URL('..', import.meta.url)))
const outputBase = join(repoRoot, 'output', 'thread-task-board-smoke')
mkdirSync(outputBase, { recursive: true })

const outputRoot = mkdtempSync(join(outputBase, 'run-'))
const entryPath = join(outputRoot, 'entry.ts')
const bundledPath = join(outputRoot, 'entry.mjs')
const boardImport = toImportPath(
  relative(outputRoot, join(repoRoot, 'src', 'task-board', 'projectThreadTaskBoard.ts')),
)

try {
  writeFileSync(entryPath, buildEntrySource(boardImport), 'utf8')

  await esbuild.build({
    bundle: true,
    entryPoints: [entryPath],
    format: 'esm',
    logLevel: 'silent',
    outfile: bundledPath,
    platform: 'node',
    target: 'node22',
  })

  const result = spawnSync(process.execPath, [bundledPath], {
    cwd: repoRoot,
    stdio: 'inherit',
    shell: false,
  })

  if (result.status !== 0) {
    const reason = result.error ? ': ' + result.error.message : ''
    throw new Error('verify-thread-task-board failed with exit code ' + String(result.status) + reason)
  }
} finally {
  if (process.env.CX_CODEX_KEEP_THREAD_TASK_BOARD_SMOKE_OUTPUT !== '1') {
    rmSync(outputRoot, { recursive: true, force: true })
  }
}

